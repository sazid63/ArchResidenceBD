"""Build the offline manual that ships with the install.

    uv run --directory core python ../tools/install/build_manual.py --write
    uv run --directory core python ../tools/install/build_manual.py --check
    uv run --directory core python ../tools/install/build_manual.py --search "soil report"

The manual is **derived from the repo's own facts** ✓ — the flow book ✓ (the questions the
app asks ✓ and why ✓) and the rule packs ✓ (the provisions the app applies ✓, with their
clauses ✓) — so it is generated by a script ✓ and never by a model ✓ ✓.

The search is **deterministic** ✓ and needs no network and no model ✓ ✓ — the app's
offline help ✓ ✓.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

from archres_core.manual import build_manual, manual_document, search_manual
from archres_core.stdio import utf8_stdio

ROOT = pathlib.Path(__file__).resolve().parents[2]
BOOK = ROOT / "spec" / "flows" / "phase-flow-book.yaml"
PACK_DIR = ROOT / "spec" / "rules"
OUT = ROOT / "data" / "install" / "manual.json"


def _packs() -> list[pathlib.Path]:
    return sorted(path for path in PACK_DIR.glob("*.yaml"))


def main(argv: list[str] | None = None) -> int:
    utf8_stdio()
    parser = argparse.ArgumentParser(
        description="Build the offline manual (derived from the flow book and the rule packs)."
    )
    parser.add_argument("--out", default=str(OUT), help="where the manual is written")
    parser.add_argument("--write", action="store_true", help="write the manual")
    parser.add_argument("--check", action="store_true", help="fail when the manual is stale")
    parser.add_argument("--search", help="search the manual and print the answers")
    parser.add_argument("--lang", default="en", help="the language to search in (en or bn)")
    args = parser.parse_args(argv)

    entries = build_manual(BOOK, _packs())
    document = manual_document(entries)

    if args.search:
        hits = search_manual(entries, args.search, lang=args.lang)
        if not hits:
            print(f"nothing in the manual answers {args.search!r}")
            return 0
        for entry, score in hits:
            print(f"  {score:.2f}  {entry.id}  [{entry.source}]")
            print(f"        {entry.question.get(args.lang, '')}")
            print(f"        {entry.answer.get(args.lang, '')}")
        return 0

    text = json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    target = pathlib.Path(args.out)
    if args.check:
        if not target.is_file():
            print(f"FAIL the manual is missing: {target}")
            return 1
        if target.read_text(encoding="utf-8") != text:
            print(f"FAIL the manual is stale: {target}")
            return 1
        print(f"the manual is fresh: {document['counts']['entries']} entries")
        return 0
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(
            f"wrote {target}: {document['counts']['entries']} entries in "
            f"{document['counts']['topics']} topics - offline, no model"
        )
        return 0
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
