"""The foundation designer (W2.2): deterministic, provenance-carrying, and honest about gaps."""

from __future__ import annotations

import json
import pathlib

import pytest

from archres_core.design.foundation import PROVENANCE_SPEC
from archres_core.design import (
    DesignError,
    design_foundation,
    render_macro,
)

ROOT = pathlib.Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "spec" / "examples"


def _spec(name: str = "two-storey-residential.json") -> dict:
    return json.loads((EXAMPLES / name).read_text(encoding="utf-8"))


def test_the_design_is_deterministic() -> None:
    spec = _spec()
    first = design_foundation(spec)
    second = design_foundation(spec)
    assert first.as_dict() == second.as_dict()
    assert render_macro(first) == render_macro(second)


def test_every_number_carries_its_provenance() -> None:
    design = design_foundation(_spec())
    assert design.values
    for key, value in design.values.items():
        assert value.provenance in ("spec", "derived", "assumed"), key
        assert value.source, key
        assert value.unit, key
    assert design.values["plot.areaSqm"].provenance == "spec"
    assert design.values["plot.depthM"].provenance == "derived"
    assert design.values["footing.sizeMm"].provenance == "assumed"


def test_the_assumptions_are_handed_back_for_the_spec() -> None:
    design = design_foundation(_spec())
    assert design.assumptions
    pointers = {item.pointer for item in design.assumptions}
    assert "/phases/foundation/data/footingSizeMm" in pointers
    # the depth comes from the spec, so there is nothing to hand back for it - and what is
    # handed back points at the spec's own keys, so the app writes where the design reads.
    assert "/phases/foundation/data/footingDepthM" not in pointers
    assert all(
        pointer.startswith(("/phases/foundation/data/", "/phases/site-excavation/data/"))
        for pointer in pointers
    ), pointers
    for item in design.assumptions:
        assert item.reason, item.pointer
        assert item.unit in ("mm", "m"), item.pointer


def test_the_foundation_reads_back_what_it_hands_back() -> None:
    """The loop closes: a value the app writes into the spec is honoured."""
    spec = _spec()
    for phase in spec["phases"]:
        if phase["id"] == "foundation":
            phase.setdefault("data", {})["footingSizeMm"] = 1000.0
    design = design_foundation(spec)
    assert design.footings[0].size_x_mm == 1000.0
    assert design.values["footing.sizeMm"].provenance == PROVENANCE_SPEC
    pointers = {item.pointer for item in design.assumptions}
    assert "/phases/foundation/data/footingSizeMm" not in pointers


def test_a_spec_without_a_usable_plot_is_refused() -> None:
    spec = _spec()
    spec["site"]["plot"]["areaSqm"] = 0
    with pytest.raises(DesignError, match="areaSqm"):
        design_foundation(spec)
    spec = _spec()
    del spec["site"]["plot"]["frontageM"]
    with pytest.raises(DesignError, match="frontageM"):
        design_foundation(spec)


def test_the_footings_sit_on_the_grid_inside_the_plot() -> None:
    spec = _spec()
    design = design_foundation(spec)
    frontage_mm = spec["site"]["plot"]["frontageM"] * 1000.0
    assert len(design.footings) >= 2
    for footing in design.footings:
        assert 0 <= footing.x_mm <= frontage_mm
        assert footing.size_x_mm == 1200.0
        # the spec's footing depth (1.5 m), not the v0 assumption - the spec wins
    assert footing.depth_mm == 1500.0
    assert design.footings[0].x_mm < design.footings[-1].x_mm
    assert len(design.grade_beams) == len(design.footings) - 1
    for beam in design.grade_beams:
        assert beam.length_mm > 0
        assert beam.from_id != beam.to_id


def test_the_expected_objects_come_from_the_design() -> None:
    design = design_foundation(_spec())
    expected = design.expected_objects()
    assert len(expected) == len(design.footings) + len(design.grade_beams)
    names = [item["name"] for item in expected]
    assert names[0].startswith("Footing_")
    assert "GradeBeam_GB1" in names
    footing = design.footings[0]
    assert expected[0]["volumeM3"] == pytest.approx(
        footing.size_x_mm * footing.size_y_mm * footing.depth_mm / 1e9, rel=1e-6
    )


def test_the_macro_is_valid_python_and_carries_the_design() -> None:
    design = design_foundation(_spec())
    macro = render_macro(design)
    compile(macro, "<generated macro>", "exec")
    assert "GENERATED by archres_core.design.foundation" in macro
    for footing in design.footings:
        assert f'"id": "{footing.id}"' in macro
    assert "Footing_" in macro and "GradeBeam_" in macro
    # The macro must not invent numbers: every footing size in the text comes from the design.
    assert str(int(design.footings[0].size_x_mm)) in macro


def test_the_excavation_is_declared_not_a_solid() -> None:
    design = design_foundation(_spec())
    assert design.excavation.volume_m3 > 0
    macro = render_macro(design)
    assert "Excavation" not in macro, "the excavation is declared, not built, in v0"
    assert "foundation-design.json" in macro


def test_the_design_reports_its_totals() -> None:
    design = design_foundation(_spec())
    payload = design.as_dict()
    assert payload["totals"]["footingVolumeM3"] > 0
    assert payload["totals"]["excavationVolumeM3"] > 0
    assert payload["excavation"]["depthMm"] > 0
