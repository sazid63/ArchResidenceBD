"""The drawing sheet design (W2.5): computed, reproducible, and ours."""

from __future__ import annotations

import json
import pathlib

import pytest

from archres_core.design import (
    SCALE_LABEL,
    SHEET_STATUS,
    design_foundation,
    design_sheet,
    design_typical_floor,
    render_sheet_macro,
)

ROOT = pathlib.Path(__file__).resolve().parents[2]
EXAMPLE = ROOT / "spec" / "examples" / "two-storey-residential.json"


def _design():
    spec = json.loads(EXAMPLE.read_text(encoding="utf-8"))
    foundation = design_foundation(spec)
    floor = design_typical_floor(spec, foundation, storey_index=1)
    return spec, foundation, floor, design_sheet(spec, foundation, floor)


def test_the_sheet_design_is_deterministic() -> None:
    _spec, _foundation, _floor, first = _design()
    _spec2, _foundation2, _floor2, second = _design()
    assert first.as_dict() == second.as_dict()
    assert render_sheet_macro(first) == render_sheet_macro(second)


def test_the_sheet_carries_the_model_it_draws() -> None:
    _spec, foundation, floor, design = _design()
    kinds = {box["kind"] for box in design.model}
    assert kinds == {"footing", "column", "slab"}
    assert len([box for box in design.model if box["kind"] == "footing"]) == len(foundation.footings)
    assert len([box for box in design.model if box["kind"] == "column"]) == len(floor.columns)


def test_the_dimensions_are_computed_from_the_design() -> None:
    _spec, _foundation, _floor, design = _design()
    values = design.values
    assert values["sheet.overallWidthMm"].provenance == "derived"
    assert values["sheet.overallWidthMm"].value > 0
    assert values["sheet.gridSpacingMm"].provenance == "derived"
    labels = {item.label for item in design.dimensions}
    assert any(label.endswith(" m") for label in labels)
    # The plan's width dimension is the model's own width, not a number from elsewhere.
    width = values["sheet.overallWidthMm"].value
    assert f"{width / 1000.0:.2f} m" in labels


def test_the_sheet_states_its_scale_and_its_status() -> None:
    _spec, _foundation, _floor, design = _design()
    assert design.scale_label == SCALE_LABEL
    assert SHEET_STATUS.startswith("Candidate")
    assert design.values["sheet.scale"].provenance == "assumed"


def test_the_two_views_are_a_plan_and_an_elevation() -> None:
    _spec, _foundation, _floor, design = _design()
    labels = {view["label"] for view in design.views}
    assert any("PLAN" in label for label in labels)
    assert any("ELEVATION" in label for label in labels)
    directions = {tuple(view["direction"]) for view in design.views}
    assert (0.0, 0.0, 1.0) in directions
    assert (0.0, -1.0, 0.0) in directions


def test_the_macro_is_valid_python_and_carries_the_design() -> None:
    _spec, _foundation, _floor, design = _design()
    macro = render_sheet_macro(design)
    compile(macro, "<generated sheet macro>", "exec")
    assert "GENERATED by archres_core.design.drawing" in macro
    assert design.drawing_number in macro
    assert SHEET_STATUS in macro
    # The brand guard lives in the generator, not in a reviewer's memory.
    assert "freecad" in macro.lower()  # the guard that strips it is in the macro
    assert "the engine name leaked into the composed sheet" in macro
