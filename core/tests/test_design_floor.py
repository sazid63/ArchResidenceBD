"""The typical floor designer (W2.3): the storey rides the foundation's grid."""

from __future__ import annotations

import json
import pathlib

import pytest

from archres_core.design import (
    DesignError,
    design_foundation,
    design_typical_floor,
    render_floor_macro,
)

ROOT = pathlib.Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "spec" / "examples"


def _spec(name: str = "two-storey-residential.json") -> dict:
    return json.loads((EXAMPLES / name).read_text(encoding="utf-8"))


def _floor(storey_index: int = 1):
    spec = _spec()
    foundation = design_foundation(spec)
    return spec, foundation, design_typical_floor(spec, foundation, storey_index=storey_index)


def test_the_floor_rides_the_foundation_grid() -> None:
    _spec_obj, foundation, floor = _floor()
    assert len(floor.columns) == len(foundation.footings)
    for column, footing in zip(floor.columns, foundation.footings, strict=True):
        assert column.x_mm == footing.x_mm
        assert column.y_mm == footing.y_mm
        assert column.footing_id == footing.id


def test_the_storey_height_comes_from_the_spec() -> None:
    spec, _foundation, floor = _floor(storey_index=1)
    expected = spec["building"]["storeys"]["typicalFloorHeightM"]
    assert floor.values["storey.heightM"].value == expected
    assert floor.values["storey.heightM"].provenance == "spec"
    assert floor.columns[0].height_mm == pytest.approx(expected * 1000.0, rel=1e-6)


def test_the_ground_storey_uses_its_own_height() -> None:
    spec, _foundation, floor = _floor(storey_index=0)
    expected = spec["building"]["storeys"]["groundFloorHeightM"]
    assert floor.values["storey.heightM"].value == expected
    assert floor.values["storey.heightM"].source == "/building/storeys/groundFloorHeightM"


def test_the_storeys_stack_on_top_of_each_other() -> None:
    spec, _foundation, ground = _floor(storey_index=0)
    _spec_obj, _foundation2, first = _floor(storey_index=1)
    assert ground.base_z_mm == 0.0
    expected = spec["building"]["storeys"]["groundFloorHeightM"] * 1000.0
    assert first.base_z_mm == pytest.approx(expected, rel=1e-6)
    assert first.values["storey.baseElevationM"].provenance == "derived"
    # The storey above starts where the one below ends, and the expectation carries the
    # elevation so the engine can be asked where the shape actually sits.
    column = first.columns[0]
    expected_objects = first.expected_objects()
    assert expected_objects[0]["bboxZMm"] == [first.base_z_mm, first.base_z_mm + column.height_mm]


def test_a_spec_without_a_storey_height_is_refused() -> None:
    spec = _spec()
    del spec["building"]["storeys"]["typicalFloorHeightM"]
    del spec["building"]["storeys"]["groundFloorHeightM"]
    foundation = design_foundation(spec)
    with pytest.raises(DesignError, match="storey height"):
        design_typical_floor(spec, foundation, storey_index=1)


def test_the_slab_thickness_comes_from_the_floor_phase() -> None:
    spec, _foundation, floor = _floor(storey_index=1)
    expected = spec["phases"][3]["data"]["slabThicknessMm"]
    assert floor.values["slab.thicknessMm"].value == expected
    assert floor.values["slab.thicknessMm"].provenance == "spec"


def test_the_walls_and_openings_are_declared_absent_not_invented() -> None:
    _spec_obj, _foundation, floor = _floor()
    assert floor.declared_absent
    joined = " ".join(floor.declared_absent)
    assert "walls" in joined
    assert "openings" in joined
    macro = render_floor_macro(floor)
    assert "Wall" not in macro, "no wall may be built without spec data"


def test_the_expected_objects_come_from_the_design() -> None:
    _spec_obj, _foundation, floor = _floor()
    expected = floor.expected_objects()
    names = [item["name"] for item in expected]
    assert names[0].startswith("Column_")
    assert names[-1] == "Slab_1"
    column = floor.columns[0]
    assert expected[0]["volumeM3"] == pytest.approx(
        column.size_mm * column.size_mm * column.height_mm / 1e9, rel=1e-6
    )


def test_the_floor_macro_is_valid_python_and_deterministic() -> None:
    _spec_obj, _foundation, floor = _floor()
    macro = render_floor_macro(floor)
    compile(macro, "<generated macro>", "exec")
    assert render_floor_macro(floor) == macro
    assert "GENERATED by archres_core.design.floor" in macro
    for column in floor.columns:
        assert f'"id": "{column.id}"' in macro


def test_the_assumptions_are_handed_back() -> None:
    _spec_obj, _foundation, floor = _floor()
    pointers = {item.pointer for item in floor.assumptions}
    assert "/phases/floor/data/columnSizeMm" in pointers
    assert "/phases/floor/data/beamMm" in pointers
    for item in floor.assumptions:
        assert item.reason
