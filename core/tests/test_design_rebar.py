"""The rebar designer and the BBS data model (W2.4): steel with provenance, and a schedule."""

from __future__ import annotations

import json
import math
import pathlib

import pytest

from archres_core.design import (
    BBS_SCHEMA_VERSION,
    STEEL_DENSITY_KG_PER_M3,
    build_bbs,
    design_foundation,
    design_rebar,
    design_typical_floor,
    render_rebar_macro,
)

ROOT = pathlib.Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "spec" / "examples"


def _design():
    spec = json.loads((EXAMPLES / "two-storey-residential.json").read_text(encoding="utf-8"))
    foundation = design_foundation(spec)
    floor = design_typical_floor(spec, foundation, storey_index=1)
    return spec, foundation, floor, design_rebar(spec, foundation, floor)


def test_the_rebar_design_is_deterministic() -> None:
    _spec, _foundation, _floor, first = _design()
    _spec2, _foundation2, _floor2, second = _design()
    assert first.as_dict() == second.as_dict()
    assert render_rebar_macro(first) == render_rebar_macro(second)


def test_every_member_gets_steel() -> None:
    _spec, foundation, floor, design = _design()
    members = {bar.member for bar in design.bars}
    assert {column.id for column in floor.columns} <= members
    assert {beam.id for beam in floor.beams} <= members
    assert {footing.id for footing in foundation.footings} <= members


def test_the_detailing_assumptions_are_handed_back() -> None:
    _spec, _foundation, _floor, design = _design()
    pointers = {item.pointer for item in design.assumptions}
    assert "/phases/foundation/data/rebarCoverMm" in pointers
    assert "/phases/foundation/data/linkDiameterMm" in pointers
    assert "/phases/foundation/data/linkSpacingMm" in pointers
    for item in design.assumptions:
        assert item.reason
    assert design.values["rebar.coverMm"].provenance == "assumed"
    assert design.values["rebar.columnCount"].provenance == "derived"


def test_the_bbs_totals_match_the_items() -> None:
    _spec, _foundation, _floor, design = _design()
    bbs = build_bbs(design)
    assert bbs["schemaVersion"] == BBS_SCHEMA_VERSION
    assert bbs["items"]
    total = round(sum(item["weightKg"] for item in bbs["items"]), 4)
    assert bbs["totals"]["weightKg"] == total
    assert bbs["totals"]["barCount"] == sum(item["count"] for item in bbs["items"])
    assert bbs["densityKgPerM3"] == STEEL_DENSITY_KG_PER_M3
    for item in bbs["items"]:
        assert item["shape"] in ("straight", "link", "starter")
        assert item["count"] > 0
        assert item["lengthMm"] > 0


def test_the_weight_follows_the_pi_over_four_law() -> None:
    _spec, _foundation, _floor, design = _design()
    bar = design.bars[0]
    area = math.pi / 4.0 * (bar.diameter_mm / 1000.0) ** 2
    expected = round(bar.length_mm / 1000.0 * area * STEEL_DENSITY_KG_PER_M3 * bar.count, 4)
    assert bar.weight_kg == expected
    # The volume the engine will measure is the same steel, in cubic metres.
    volume = bar.count * bar.length_mm / 1000.0 * area
    expected_object = design.expected_objects()[0]
    assert expected_object["volumeM3"] == pytest.approx(volume, abs=1e-9)
    assert expected_object["name"] == "Rebar_" + bar.mark.replace("-", "_")


def test_the_bbs_validates_against_the_frozen_schema() -> None:
    import jsonschema

    schema = json.loads(
        (ROOT / "spec" / "schemas" / "bbs.schema.json").read_text(encoding="utf-8")
    )
    _spec, _foundation, _floor, design = _design()
    bbs = build_bbs(design)
    jsonschema.Draft202012Validator(schema).validate(bbs)
    # The committed fixture must be the same document the builder produces.
    committed = json.loads(
        (ROOT / "data" / "cad" / "generated" / "rebar-two-storey-residential.bbs.json").read_text(
            encoding="utf-8"
        )
    )
    assert committed == bbs


def test_the_rebar_macro_is_valid_python() -> None:
    _spec, _foundation, _floor, design = _design()
    macro = render_rebar_macro(design)
    compile(macro, "<generated macro>", "exec")
    assert "GENERATED by archres_core.design.rebar" in macro
    for bar in design.bars:
        assert f'"mark": "{bar.mark}"' in macro
