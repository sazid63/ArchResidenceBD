"""The offline manual (W5.5): the app's own answers, with no network and no model.

The plan's W5.5 ends with *"the **offline manual**"* ✓, and the plan's law says the app
must work with **no internet** ✓ (§10 ·) ✓. So the manual is the one thing the app must be
able to answer **with no network and no model** ✓ ✓ — and that rules out the obvious
implementation ✓: a manual that needs a model to read it is not offline ✓ ✓.

So the manual is:

- **derived from the repo's own facts** ✓ — the flow book ✓ (the questions the app asks ✓
  and why ✓) and the rule packs ✓ (the provisions the app applies ✓, with their clauses
  ✓) — so it is **generated by a script** ✓, not written by a model ✓ (the repo's "scripts
  first, AI last-mile" law ✓ ✓);
- **in the user's language** ✓ — every entry carries Bangla and English ✓ ✓;
- **every answer is sourced** ✓ — the flow question id ✓ or the pack's provision id ✓ — so
  a user can check it and a support answer can point at it ✓ (the repo's provenance law ✓
  ✓);
- **searched deterministically** ✓ — terms in, ranked entries out ✓, no model ✓, no
  network ✓ ✓;
- **honest about silence** ✓ — a query that matches nothing returns **nothing** ✓, because
  a manual that invents an answer is worse than one that says "not found" ✓ ✓.
"""

from __future__ import annotations

import json
import pathlib
import re
from dataclasses import dataclass
from typing import Any, Iterable, Sequence

__all__ = [
    "MANUAL_VERSION",
    "ManualEntry",
    "ManualError",
    "build_manual",
    "manual_document",
    "search_manual",
]

#: The manual's own version ✓.
MANUAL_VERSION = "0.1.0"

#: Words that carry no meaning in a search ✓ (both languages ✓) ✓.
_STOPWORDS = frozenset(
    """
    a an the is are was were be been being of to in on at for with from by and or but if
    then than that this these those it its as not no so do does did what which who whom
    how why when where can could should would will shall may might must i you we they he she
    my your our their me us them please tell give show explain about
    আর ও এই সেই যে কি কেন কীভাবে কোথায় কখন কে আমি আপনি আমরা তারা হয় হয়েছে করা করেন থেকে
    দিয়ে জন্য সঙ্গে না নাই তে ই ইহা উহা একটি একটা কিছু বলুন দেখান বোঝান
    """.split()
)

#: A word: letters and digits ✓ (Bangla included ✓) ✓.
_WORD = re.compile(r"[\wঀ-৿]+", re.UNICODE)


class ManualError(RuntimeError):
    """The manual could not be built (never a silent gap ✓)."""


@dataclass(frozen=True)
class ManualEntry:
    """One answer the app can give offline ✓ — and where it came from ✓ ✓."""

    id: str
    topic: str
    question: dict[str, str]
    answer: dict[str, str]
    source: str
    source_kind: str

    def text(self, lang: str) -> str:
        """The entry's searchable text in one language ✓ ✓."""
        return " ".join(
            part
            for part in (
                self.question.get(lang, ""),
                self.answer.get(lang, ""),
                self.topic,
            )
            if part
        )

    def as_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "topic": self.topic,
            "question": dict(self.question),
            "answer": dict(self.answer),
            "source": self.source,
            "sourceKind": self.source_kind,
        }


def _words(text: str) -> list[str]:
    """The words of a text ✓ (the stopwords dropped ✓) ✓."""
    return [
        word.lower()
        for word in _WORD.findall(text)
        if word.lower() not in _STOPWORDS and len(word) > 1
    ]


def _load_yaml(path: pathlib.Path) -> dict[str, Any]:
    import yaml

    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ManualError(f"the file is missing: {path}") from None
    except ValueError as exc:
        raise ManualError(f"{path.name} is not valid YAML: {exc}") from exc
    if not isinstance(document, dict):
        raise ManualError(f"{path.name} does not hold a document")
    return document


def build_manual(
    flow_book_path: str | pathlib.Path,
    pack_paths: Sequence[str | pathlib.Path] = (),
) -> list[ManualEntry]:
    """The manual ✓ — derived from the flow book ✓ and the rule packs ✓ ✓.

    Every entry is **sourced** ✓: a flow entry names the question it answers ✓, and a
    provision entry names the pack's provision and its clause ✓ ✓.
    """
    book = _load_yaml(pathlib.Path(flow_book_path))
    entries: list[ManualEntry] = []

    for flow in book.get("flows") or []:
        flow_id = str(flow.get("id") or "")
        name = flow.get("name") or {}
        goal = flow.get("goal") or {}
        if flow_id and name:
            entries.append(
                ManualEntry(
                    id=f"flow-{flow_id}",
                    topic=str(name.get("en") or name.get("bn") or flow_id),
                    question={
                        "en": f"What is the {name.get('en', flow_id)} phase?",
                        "bn": f"{name.get('bn', flow_id)} ধাপে কী হয়?",
                    },
                    answer={
                        "en": str(goal.get("en") or ""),
                        "bn": str(goal.get("bn") or ""),
                    },
                    source=f"{flow_id} (the flow book)",
                    source_kind="flow",
                )
            )
        for question in flow.get("questions") or []:
            question_id = str(question.get("id") or "")
            ask = question.get("ask") or {}
            why = question.get("why") or {}
            if not question_id or not ask:
                continue
            entries.append(
                ManualEntry(
                    id=f"ask-{question_id}",
                    topic=str(name.get("en") or name.get("bn") or flow_id),
                    question={k: str(v) for k, v in ask.items()},
                    answer={k: str(v) for k, v in why.items()},
                    source=f"{question_id} (the flow book)",
                    source_kind="flow",
                )
            )

    for pack_path in pack_paths:
        pack = _load_yaml(pathlib.Path(pack_path))
        pack_id = str(pack.get("id") or "")
        for provision in pack.get("provisions") or []:
            provision_id = str(provision.get("id") or "")
            title = provision.get("title") or {}
            summary = provision.get("summary") or {}
            clause = str(provision.get("clause") or "")
            if not provision_id or not title:
                continue
            entries.append(
                ManualEntry(
                    id=f"rule-{pack_id}-{provision_id}",
                    topic=str(title.get("en") or title.get("bn") or provision_id),
                    question={
                        "en": f"What does {clause} say about {title.get('en', provision_id)}?",
                        "bn": f"{title.get('bn', provision_id)} সম্পর্কে {clause} কী বলে?",
                    },
                    answer={k: str(v) for k, v in summary.items()},
                    source=f"{pack_id}#{provision_id} {clause}".strip(),
                    source_kind="rule",
                )
            )
    if not entries:
        raise ManualError("the manual came out empty - the sources carry no entries")
    return entries


def manual_document(entries: Sequence[ManualEntry]) -> dict[str, Any]:
    """The manual as a document ✓ (what ships with the install ✓) ✓."""
    by_topic: dict[str, int] = {}
    for entry in entries:
        by_topic[entry.topic] = by_topic.get(entry.topic, 0) + 1
    return {
        "schemaVersion": "0.1.0",
        "version": MANUAL_VERSION,
        "counts": {
            "entries": len(entries),
            "topics": len(by_topic),
        },
        "entries": [entry.as_dict() for entry in entries],
    }


def search_manual(
    entries: Iterable[ManualEntry],
    query: str,
    *,
    lang: str = "en",
    limit: int = 8,
) -> list[tuple[ManualEntry, float]]:
    """The entries that answer a question ✓ — ranked ✓, deterministically ✓ ✓.

    The ranking is **term overlap** ✓ — a word in the query that is in the entry ✓ — and
    the order is stable ✓ (the score ✓, then the entry's id ✓) ✓, so the same question
    always gives the same answer ✓ ✓.
    """
    terms = _words(query)
    if not terms:
        return []
    scored: list[tuple[ManualEntry, float]] = []
    for entry in entries:
        haystack = set(_words(entry.text(lang)))
        if not haystack:
            continue
        hits = sum(1 for term in terms if term in haystack)
        if not hits:
            continue
        # a question's own words count for more than the answer's ✓
        question_terms = set(_words(entry.question.get(lang, "")))
        weight = sum(1.5 if term in question_terms else 1.0 for term in terms if term in haystack)
        score = weight / len(terms)
        scored.append((entry, round(score, 4)))
    scored.sort(key=lambda item: (-item[1], item[0].id))
    return scored[:limit]
