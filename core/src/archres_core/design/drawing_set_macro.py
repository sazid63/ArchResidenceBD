"""The set's macro (W3.3): every sheet, one PDF.

The composer is W2.5's, run per sheet: each sheet gets its own TechDraw page, its own
title-block fields, its own SVG and its own DXF, and all the sheets go into **one PDF, one page
each** — the file an engineer sends ✓.

The engine's name never reaches the paper ✓ (the same guard W2.5 uses ✓) and the sheet carries
the pack's "candidate - not for construction" status ✓.
"""

from __future__ import annotations

import json
from typing import Any

from .drawing import SHEET_STATUS
from .drawing_set import DrawingSet


def render_set_macro(design: DrawingSet) -> str:
    """The deterministic FreeCAD macro that composes the whole set."""
    payload = {
        "projectId": design.project_id,
        "projectName": design.project_name,
        "drawingNumber": design.drawing_number,
        "issuedOn": design.issued_on,
        "scaleLabel": design.scale_label,
        "status": SHEET_STATUS,
        "sheets": [sheet.as_dict() for sheet in design.sheets],
    }
    return (
        '''"""Drawing set (W3.3) - GENERATED by archres_core.design.drawing_set."""

import json
import math
import os
import pathlib
import re

import FreeCAD as App
import Part
import TechDraw

DESIGN = json.loads(r"""'''
        + json.dumps(payload, ensure_ascii=False, indent=1, sort_keys=True)
        + '''
""")

OUT = pathlib.Path(os.environ["ARCHRES_JOB_OUTDIR"])
RES = pathlib.Path(App.getResourceDir())
TEMPLATE = RES / "Mod" / "TechDraw" / "Templates" / "ISO" / "A4_Landscape_ISO5457_advanced.svg"
FONT = RES / "Mod" / "TechDraw" / "Resources" / "fonts" / "osifont-lgpl3fe.ttf"

PAGE_W_MM = 297.0
PAGE_H_MM = 210.0
SCALE = 1.0 / 30.0
TEXT_MM = 2.5


def build_model(sheet):
    document = App.ActiveDocument
    structure = document.addObject("Part::Feature", "Structure")
    shapes = []
    for box in sheet["model"]:
        shape = Part.makeBox(
            box["lMm"],
            box["wMm"],
            box["hMm"],
            App.Vector(box["xMm"], box["yMm"], box["zMm"]),
        )
        shapes.append(shape)
    structure.Shape = Part.makeCompound(shapes)
    return structure


def to_svg_y(y_mm):
    return PAGE_H_MM - y_mm


def view_group(frag, x_mm, y_mm):
    min_x, min_y, width, height = frag["bounds"]
    dx = x_mm - (min_x + width / 2.0)
    dy = y_mm - (min_y + height / 2.0)
    return (
        "<g transform='translate("
        + f"{dx:.3f},{dy:.3f}"
        + ")'>" + frag["svg"] + "</g>"
    )


def dim_lines_and_texts(dim, x_mm, y_mm, half_w, half_h):
    value = dim["label"]
    if dim["axis"] == "h":
        x1, y1 = x_mm - half_w, y_mm - half_h - 8.0
        x2, y2 = x_mm + half_w, y_mm - half_h - 8.0
        tx, ty = x_mm, y_mm - half_h - 10.5
        lines = (
            f"<line x1='{x1:.2f}' y1='{to_svg_y(y1):.2f}' x2='{x2:.2f}' y2='{to_svg_y(y2):.2f}'/>"
            f"<line x1='{x1:.2f}' y1='{to_svg_y(y1 - 2):.2f}' x2='{x1:.2f}' y2='{to_svg_y(y1 + 2):.2f}'/>"
            f"<line x1='{x2:.2f}' y1='{to_svg_y(y2 - 2):.2f}' x2='{x2:.2f}' y2='{to_svg_y(y2 + 2):.2f}'/>"
        )
        text = (
            f"<text x='{tx:.2f}' y='{to_svg_y(ty):.2f}' font-size='{TEXT_MM}' "
            f"font-family='osifont, sans-serif' text-anchor='middle'>{value}</text>"
        )
    else:
        x1, y1 = x_mm + half_w + 8.0, y_mm - half_h
        x2, y2 = x_mm + half_w + 8.0, y_mm + half_h
        tx, ty = x_mm + half_w + 12.0, y_mm
        lines = (
            f"<line x1='{x1:.2f}' y1='{to_svg_y(y1):.2f}' x2='{x2:.2f}' y2='{to_svg_y(y2):.2f}'/>"
            f"<line x1='{x1 - 2:.2f}' y1='{to_svg_y(y1):.2f}' x2='{x1 + 2:.2f}' y2='{to_svg_y(y1):.2f}'/>"
            f"<line x1='{x2 - 2:.2f}' y1='{to_svg_y(y2):.2f}' x2='{x2 + 2:.2f}' y2='{to_svg_y(y2):.2f}'/>"
        )
        text = (
            f"<text x='{tx:.2f}' y='{to_svg_y(ty):.2f}' font-size='{TEXT_MM}' "
            f"font-family='osifont, sans-serif' text-anchor='middle'>{value}</text>"
        )
    return lines, text


def label(x_mm, y_mm, text):
    return (
        f"<text x='{x_mm:.2f}' y='{to_svg_y(y_mm):.2f}' font-size='{TEXT_MM}' "
        f"font-family='osifont, sans-serif' text-anchor='middle'>{text}</text>"
    )


def compose(sheet, index, total):
    """One sheet: its page, its views, its title block, its annotation, its files."""
    document = App.ActiveDocument
    structure = build_model(sheet)

    page = document.addObject("TechDraw::DrawPage", f"Page{index}")
    template = document.addObject("TechDraw::DrawSVGTemplate", f"Template{index}")
    template.Template = str(TEMPLATE)
    page.Template = template

    views = {}
    for view in sheet["views"]:
        part = document.addObject("TechDraw::DrawViewPart", f"View_{view['id']}_{index}")
        part.Source = [structure]
        part.Direction = App.Vector(*view["direction"])
        part.ScaleType = "Custom"
        part.Scale = SCALE
        page.addView(part)
        part.X = view["xMm"]
        part.Y = view["yMm"]
        views[view["id"]] = part
    document.recompute()

    fragments = {}
    for key, view in views.items():
        svg = TechDraw.viewPartAsSvg(view)
        xs, ys = [], []
        for path in re.findall(r'd="([^"]+)"', svg):
            for match in re.finditer(r"(-?\\d+(?:\\.\\d+)?)\\s+(-?\\d+(?:\\.\\d+)?)", path):
                xs.append(float(match.group(1)))
                ys.append(float(match.group(2)))
        if not xs:
            raise RuntimeError("the view fragment is empty: " + key)
        fragments[key] = {
            "svg": svg,
            "bounds": (min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)),
        }

    composed_sheet = TEMPLATE.read_text(encoding="utf-8")
    fields = {
        "<tspan>ISO 7200 titleblock</tspan>": "<tspan>ArchResidenceBD</tspan>",
        "<tspan>ST1</tspan>": "<tspan>" + sheet["sheetTitle"] + "</tspan>",
        "<tspan>ST2</tspan>": "<tspan>" + DESIGN["status"] + "</tspan>",
        "<tspan>DN</tspan>": "<tspan>" + sheet["drawingNumber"] + "</tspan>",
        "<tspan>AAA</tspan>": "<tspan>v0</tspan>",
        "<tspan>YYYY-MM-DD</tspan>": "<tspan>" + sheet["issuedOn"] + "</tspan>",
        "<tspan>X / Y</tspan>": "<tspan>" + str(index) + " / " + str(total) + "</tspan>",
        "<tspan>1 : 1</tspan>": "<tspan>" + DESIGN["scaleLabel"] + "</tspan>",
        "<tspan>A. Nemesis</tspan>": "<tspan>NativeCAD (ArchResidenceBD)</tspan>",
        "<tspan>Component Drawing</tspan>": "<tspan>Design drawing</tspan>",
        "<tspan>In preparation</tspan>": "<tspan>" + DESIGN["status"] + "</tspan>",
        "<tspan>Stainless steel Mat.No. 1.4301</tspan>": "<tspan>RC footing + RC columns + slab</tspan>",
    }
    for old, new in fields.items():
        if composed_sheet.count(old) != 1:
            raise RuntimeError("template field not found exactly once: " + old)
        composed_sheet = composed_sheet.replace(old, new)

    # the brand guard (ADR-0004)
    composed_sheet = re.sub(r'\\s+xmlns:freecad="[^"]*"', "", composed_sheet)
    composed_sheet = re.sub(r'\\sfreecad:[A-Za-z_]+="[^"]*"', "", composed_sheet)

    dim_texts = ""
    for dim in sheet["dimensions"]:
        frag = fragments[dim["view"]]
        min_x, min_y, width, height = frag["bounds"]
        view = next(item for item in sheet["views"] if item["id"] == dim["view"])
        lines, text = dim_lines_and_texts(
            dim, view["xMm"], view["yMm"], width / 2.0, height / 2.0
        )
        dim_texts += lines + text
    for view in sheet["views"]:
        frag = fragments[view["id"]]
        min_x, min_y, width, height = frag["bounds"]
        dim_texts += label(
            view["xMm"], view["yMm"] + height / 2.0 + 6.0, view["label"] + "  -  " + DESIGN["scaleLabel"]
        )

    annotation = (
        "<g transform='matrix(1,0,0,-1,0," + str(PAGE_H_MM) + ")' fill='none' stroke='#000000' "
        "stroke-width='0.25'>" + dim_texts + "</g>"
    )
    groups = "".join(
        view_group(fragments[view["id"]], view["xMm"], view["yMm"]) for view in sheet["views"]
    )
    composed = composed_sheet.replace("</svg>", groups + annotation + "</svg>")
    if "freecad" in composed.lower():
        raise RuntimeError("the engine name leaked into the composed sheet")
    (OUT / f"page-{index}.svg").write_text(composed, encoding="utf-8", newline="\\n")

    TechDraw.writeDXFPage(page, str(OUT / f"page-{index}.dxf"))
    return composed


def main():
    from PySide6 import QtCore, QtGui, QtSvg

    app = QtGui.QGuiApplication.instance() or QtGui.QGuiApplication([])
    if FONT.is_file():
        QtGui.QFontDatabase.addApplicationFont(str(FONT))

    total = len(DESIGN["sheets"])
    composed_pages = []
    for index, sheet in enumerate(DESIGN["sheets"], start=1):
        composed_pages.append(compose(sheet, index, total))

    writer = QtGui.QPdfWriter(str(OUT / "drawing-set.pdf"))
    writer.setResolution(300)
    layout = QtGui.QPageLayout()
    layout.setPageSize(QtGui.QPageSize(QtGui.QPageSize.A4))
    layout.setOrientation(QtGui.QPageLayout.Orientation.Landscape)
    writer.setPageLayout(layout)
    for setter, value in (
        ("setTitle", "ArchResidenceBD - " + DESIGN["drawingNumber"]),
        ("setCreator", "NativeCAD (ArchResidenceBD)"),
        ("setProducer", "NativeCAD (ArchResidenceBD)"),
    ):
        method = getattr(writer, setter, None)
        if method is not None:
            method(value)
    painter = QtGui.QPainter()
    if not painter.begin(writer):
        raise RuntimeError("the PDF writer refused a painter")
    for index, composed in enumerate(composed_pages):
        if index > 0:
            writer.newPage()
        renderer = QtSvg.QSvgRenderer(QtCore.QByteArray(composed.encode("utf-8")))
        if not renderer.isValid():
            raise RuntimeError("a composed sheet does not parse as SVG")
        renderer.render(painter)
    painter.end()

    (OUT / "set-design.json").write_text(
        json.dumps(DESIGN, ensure_ascii=False, indent=1, sort_keys=True) + "\\n",
        encoding="utf-8",
    )
    (OUT / "set-manifest.json").write_text(
        json.dumps(
            {
                "sheets": [
                    {
                        "index": index,
                        "title": sheet["sheetTitle"],
                        "drawingNumber": sheet["drawingNumber"],
                        "views": [view["label"] for view in sheet["views"]],
                    }
                    for index, sheet in enumerate(DESIGN["sheets"], start=1)
                ],
                "total": total,
            },
            ensure_ascii=False,
            indent=1,
            sort_keys=True,
        )
        + "\\n",
        encoding="utf-8",
    )


main()
'''
    )


