/**
 * Get floor plans by unit count
 */
export function getFloorPlansByUnits(unitsCount: number): FloorPlanImage[] {
  if (unitsCount === 1) return BANGLADESH_FLOORPLANS_1UNIT;
  if (unitsCount === 2) return BANGLADESH_FLOORPLANS_2UNIT;
  return BANGLADESH_FLOORPLANS_3UNIT;
}

/**
 * Get random floor plan for given unit count
 */
export function getRandomFloorPlan(unitsCount: number): FloorPlanImage | null {
  const plans = getFloorPlansByUnits(unitsCount);
  if (plans.length === 0) return null;
  const randomIndex = Math.floor(Math.random() * plans.length);
  return plans[randomIndex];
}

/**
 * Get total count of available floor plans
 */
export function getTotalFloorPlanCount(): number {
  return BANGLADESH_FLOORPLANS_1UNIT.length + 
         BANGLADESH_FLOORPLANS_2UNIT.length + 
         BANGLADESH_FLOORPLANS_3UNIT.length;
}
